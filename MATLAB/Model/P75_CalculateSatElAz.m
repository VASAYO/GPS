function [El, Az] = P75_CalculateSatElAz(Sxyz, Uxyz, Params)
%
% Фунция производит вычисление углов места и азимута спутника
% относительно положения пользователя

% Входные переменные
%   Sxyz - массив (1 x 3) координат x, y, z спутника;
%   Uxyz - массив (1 х 3) координат x, y, z пользователя.
%
% Выходные переменные
%   El - скаляр, угол места (semicircles);
%   Az - скаляр, азимут (semicircles).

% Вычисление вектора от пользователя к спутнику
    r_vector = Sxyz - Uxyz;
    
% Извлечение компонент вектора
    dx = r_vector(1);
    dy = r_vector(2);
    dz = r_vector(3);
    
% Вычисление горизонтальной дальности
    r_horiz = sqrt(dx^2 + dy^2);
    
% Вычисление угла места (в радианах)
% El = arctan(dz / r_horiz)
    if r_horiz > 0
        El_rad = atan2(dz, r_horiz);
    else
        % Если горизонтальная дальность близка к нулю (спутник строго над головой)
        if dz > 0
            El_rad = pi/2;  % 90 градусов
        else
            El_rad = -pi/2; % -90 градусов
        end
    end
    
% Вычисление азимута (в радианах)
% Az = arctan2(dx, dy) в северно-восточной системе координат
% Обычно: 0° - север, 90° - восток
    Az_rad = atan2(dx, dy);
    
% Нормализация азимута в диапазон [0, 2*pi)
    if Az_rad < 0
        Az_rad = Az_rad + 2*pi;
    end
    
% Перевод из радиан в полуокружности (semicircles)
% 1 радиан = 1/π полуокружностей
    El = El_rad / pi;
    Az = Az_rad / pi;
    
% Обеспечение диапазона азимута [0, 2) в полуокружностях
% (соответствует [0, 2π) радиан)
    if Az >= 2
        Az = Az - 2;
    end
